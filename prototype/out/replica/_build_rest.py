# ---------------- 79 布局与视口 / 80 视口与比例 ----------------
def layout_body(scales):
    b = ["_.ZOOM _W -20,-20 460,320",
         "_.RECTANG 0,0 _D 420 297 10,10",          # A3 图幅(承接课时77 的 C 级证据)
         "_.CIRCLE 100,150 60", "_.RECTANG 220,100 340,200",
         "TILEMODE 0"]
    x = 20
    for i, s in enumerate(scales):
        b += [f"_.MVIEW {x},20 {x + 110},120"]
        x += 125
    return b


