import os

R = os.path.dirname(os.path.abspath(__file__))


def emit(n, body, note):
    b = f"{R}/l{n}/l{n}".replace("\\", "/")
    out = ["FILEDIA 0", "OSMODE 0"] + body + [
        "_.ZOOM _E", f"_.SAVEAS 2018 {b}.dwg", f"_.DXFOUT {b}.dxf 16", "_.ZOOM _E"]
    d = os.path.join(R, f"l{n}")
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, f"l{n}.scr"), "w", encoding="utf-8-sig").write("\n".join(out) + "\n")
    open(os.path.join(d, "commands.md"), "w", encoding="utf-8").write(note)
    print(f"l{n}.scr: {len(out)} lines")


# ---------------- 54 标注样式-调整 ----------------
# C 级: DIMLINEAR/DIMCONTINUE 回显 13.87 / 38.63 / 21.17
# 造一条尺寸链使三个标注刚好量得这三个值(连续标注: 13.87 -> 38.63)
x0 = 0.0
seg = [13.87, 38.63]
pts = [x0]
for s in seg:
    pts.append(pts[-1] + s)
b54 = ["DIMTXT 2.5", "DIMASZ 2.5", "_.ZOOM _W -20,-30 100,40"]
b54 += [f"_.LINE {p},0 {p},-12 " for p in pts]
b54 += [f"_.LINE {pts[0]},0 {pts[-1]},0 "]
b54 += ["_.DIMLINEAR", f"{pts[0]},0", f"{pts[1]},0", f"{(pts[0] + pts[1]) / 2:.3f},-20"]
b54 += ["_.DIMCONTINUE", f"{pts[2]},0", "", ""]
# 第三个独立标注 21.17(竖直)
b54 += ["_.LINE 80,0 80,21.17 ",
        "_.DIMLINEAR", "80,0", "80,21.17", "92,10.6"]
emit(54, b54, """# 课时54 标注样式-调整

## 证据
- **C** 命令行回显的标注文字:`13.87`(DIMCONTINUE, 289.0s)、`38.63`(293.8s)、
  `21.17`(DIMLINEAR, 465.6/472.8/479.5s 三次回显同值)
- **C** `D / DIMSTYLE` 反复开关标注样式管理器(调整选项卡);
  `ERASE 找到 6 个`(460.3s)、`ERASE 找到 1 个`(504.0s)

## 剔除
293.8/294.7/459.4/504.0s 的 `*取消*`;313.4/472.8/479.5/503.0s DIMSTYLE 打开即关闭。

## 做不到
**「调整」选项卡里的具体设置项**(文字/箭头放置方式 DIMATFIT、
文字位置 DIMTMOVE、标注特征比例 DIMSCALE、优化选项)在命令行没有回显,
对话框帧也未捕获到该选项卡 —— **一律不设、不编造**,只用默认值。
本课成品因此是"能复现那三个标注读数的几何 + 标注",不是样式设置本身。
""")

