# -*- coding: utf-8 -*-
"""课时63 特性工具 / 64 图层工具 / 66 图层补充-特性匹配。

三课共享同一套图层体系, 证据来自:
  C  `-LAYER` 的 `_ON` / `_OFF` 选项与图层名列表 —— 命令行回显
     (`输入要关闭的图层名列表: =图层2`、`输入要打开的图层名列表: =图层2` / `=0`)
  C  `_laycur 找到 1 个 / 一个对象已更改到图层 图层1 (当前图层)` —— 命令行回显
  D  特性面板: 多段线 图层=图层1, 颜色=ByLayer(色块为**绿**), 线型=ByLayer,
     全局宽度=0, 闭合=是
  L  演示图元的尺寸与摆位(视频里徒手拾取, 命令行无回显)

做不到: **图层2 的颜色/线型没有任何回显**, 画面上也无法确证哪个图元属于它;
        这里只建出该图层并复现 ON/OFF 状态切换, **不给它编造颜色**。
        线宽在 636.0s 出现过 `<线宽 >` 状态切换, 但具体值未回显。
"""
import os

R = os.path.dirname(os.path.abspath(__file__))


def emit(n, body, note):
    b = f"{R}/l{n}/l{n}".replace("\\", "/")
    out = ["FILEDIA 0", "OSMODE 0"] + body + [
        "_.ZOOM _E", f"_.SAVEAS 2018 {b}.dwg", f"_.DXFOUT {b}.dxf 16", "_.ZOOM _E"]
    d = os.path.join(R, f"l{n}")
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, f"l{n}.scr"), "w", encoding="utf-8-sig").write("\n".join(out) + "\n")
    open(os.path.join(d, "commands.md"), "w", encoding="utf-8").write(note)
    print(f"l{n}.scr: {len(out)} lines")


# 图层定义: 图层1 绿色(D 级, 特性面板色块); 图层2 只建不设色(无证据)
LAYERS = ["_.-LAYER _M 图层1 _C 3 图层1 _M 图层2 _S 0 ",
          ]

# 演示图元(L 级尺寸): 一个闭合多段线(对应特性面板里那条)、一个圆、两条斜线
GEOM = [
    "_.-LAYER _S 图层1 ",
    "_.PLINE 0,0 120,0 120,90 0,90 _CL",          # 特性面板确认: 闭合=是, 在图层1
    "_.-LAYER _S 图层2 ",
    "_.CIRCLE 260,45 50",
    "_.-LAYER _S 0 ",
    "_.LINE 360,90 500,20 ",
    "_.LINE 380,110 520,40 ",
    # 后续 CHPROP/MATCHPROP 要点选对象: 必须先把全部图元纳入视图并放大拾取框,
    # 否则单点会被当成窗选起点("Invalid window specification")
    "PICKBOX 12",
    "_.ZOOM _W -40,-40 580,160",
]

# --- 课时64 图层工具: 建层 + ON/OFF 切换 + LAYCUR ---
b64 = LAYERS + GEOM + [
    "_.-LAYER _OFF 图层2 ",      # 命令行确认: 输入要关闭的图层名列表: =图层2
    "_.-LAYER _ON 图层2 ",       # 命令行确认: 输入要打开的图层名列表: =图层2
    "_.-LAYER _ON 0 ",           # 命令行确认: =0
    "_.-LAYER _S 图层1 ",        # _laycur: 对象改到 图层1(当前图层)
    # CHPROP: 选择集与选项要逐行给, 串一行会被"选择对象"这一问吃掉
    "_.CHPROP", "360,90", "", "_LA", "图层1", "",
]
emit(64, b64, """# 课时64 图层工具

## 命令流(证据)
- `-LAYER` `_ON` / `_OFF`,图层名列表回显:`=图层2`(关)、`=图层2`(开)、`=0`(开)
- `_laycur 找到 1 个` → `一个对象已更改到图层 图层1 (当前图层)`
- 特性面板(D):多段线 图层=图层1、颜色=ByLayer(**绿**)、线型=ByLayer、
  全局宽度=0、闭合=是

## 剔除
383.5/415.7s 椭圆命令未完成;634.6/636.0s 连续 `*取消*`;
721.0/721.4s 窗选未确认;776.2s 空命令。

## 做不到
图层2 的颜色/线型无任何回显,画面也无法确证归属 —— 只建层并复现 ON/OFF,
**不编造颜色**。636.0s 的 `<线宽 >` 状态切换具体值未回显。
""")

# --- 课时63 特性工具: CHPROP 改颜色/图层/线型 ---
b63 = LAYERS + GEOM + [
    "_.CHPROP", "310,45", "", "_C", "2", "",        # 改颜色(拾取圆周)
    "_.CHPROP", "360,90", "", "_LA", "图层1", "",   # 改图层
]
emit(63, b63, """# 课时63 特性工具

## 命令流(证据)
与课时64 共享同一套图层体系(图层1 绿 / 图层2 / 0)。本课演示 PROPERTIES 面板
与 CHPROP 修改对象的颜色、图层、线型。特性面板读数(D):
多段线 图层=图层1、颜色=ByLayer(绿)、线型=ByLayer、全局宽度=0、闭合=是。

## 做不到
PROPERTIES 是模态面板,无头下无法驱动;已用命令行版 `CHPROP` 等价实现。
面板里逐项改动的**目标值**除上述几项外没有回显,未复现。
""")

# --- 课时66 图层补充-特性匹配: MATCHPROP ---
b66 = LAYERS + GEOM + [
    # MATCHPROP 在 accoreconsole 里**不存在**(既无 MATCHPROP 也无 -MATCHPROP),
    # 用 CHPROP 把目标对象改成与源对象相同的图层/颜色, 结果等价。
    "_.CHPROP", "400,72", "", "_LA", "图层1", "",
]
emit(66, b66, """# 课时66 图层补充-特性匹配

## 命令流(证据)
`MATCHPROP`(MA)选择源对象 → 选择目标对象;当前活动设置回显包含
颜色/图层/线型/线型比例/线宽/透明度/厚度/标注/文字/图案填充/多段线/视口/表格/材质/多重引线/中心对象。

## 做不到
`设置(S)` 子对话框是模态窗口,无头下无法打开,**未复现**;
视频里源/目标对象全靠鼠标拾取,无坐标回显,这里用本课自建的等价图元演示。
""")
