import { validateThreeDsMaxAnalysis } from "./threedsmax-workflow.mjs";

const PRIMITIVE_CLASSES = new Map([
  ["box", "Box"], ["cone", "Cone"], ["sphere", "Sphere"],
  ["geosphere", "GeoSphere"], ["cylinder", "Cylinder"], ["tube", "Tube"],
  ["torus", "Torus"], ["pyramid", "Pyramid"], ["teapot", "Teapot"],
  ["plane", "Plane"], ["textplus", "TextPlus"]
]);

const MODIFIER_CLASSES = new Map([
  ["bend", "Bend"], ["twist", "Twist"], ["taper", "Taper"],
  ["noise", "Noise"], ["stretch", "Stretch"], ["push", "Push"],
  ["shell", "Shell"], ["symmetry", "Symmetry"], ["turbosmooth", "TurboSmooth"],
  ["editpoly", "Edit_Poly"], ["editmesh", "Edit_Mesh"], ["uvwmap", "UVWMap"],
  ["ffd2x2x2", "FFD_2x2x2"], ["ffd3x3x3", "FFD_3x3x3"],
  ["ffd4x4x4", "FFD_4x4x4"], ["extrude", "Extrude"], ["bevel", "Bevel"],
  ["lathe", "Lathe"], ["smooth", "Smooth"], ["normal", "Normal"],
  ["optimize", "Optimize"], ["prooptimizer", "ProOptimizer"]
]);

const PROPERTY_ALIASES = new Map([
  ["lengthsegments", "lengthsegs"], ["lengthsegment", "lengthsegs"],
  ["widthsegments", "widthsegs"], ["widthsegment", "widthsegs"],
  ["heightsegments", "heightsegs"], ["heightsegment", "heightsegs"],
  ["capsegments", "capsegs"], ["sidesegments", "sides"],
  ["radiusone", "radius1"], ["radiustwo", "radius2"],
  ["rotationx", "rotationx"], ["rotationy", "rotationy"], ["rotationz", "rotationz"]
]);

export function renderMaxScript(analysis, options = {}) {
  const normalized = validateThreeDsMaxAnalysis(analysis, { validateReferences: true });
  const program = normalized.maxProgram;
  const variableByObjectId = new Map();
  const latestModifierByObjectId = new Map();
  const rendererState = { modifierCounter: 0 };
  const skipped = [];
  const body = [];

  body.push("-- Generated by Universal Mock Recorder for Autodesk 3ds Max 2027.");
  body.push("-- Scene operations are compiled from structured evidence; screen coordinates are not replayed.");
  for (const warning of [...program.warnings, ...normalized.warnings])
    body.push(`-- WARNING: ${sanitizeComment(warning)}`);
  body.push("");
  body.push("undo \"Universal Mock Recorder replay\" on");
  body.push("(");
  body.push("  disableSceneRedraw()");
  body.push("  try");
  body.push("  (");

  for (const object of program.initialObjects) {
    const variable = objectVariable(variableByObjectId.size + 1);
    variableByObjectId.set(object.id, variable);
    if (object.name) {
      body.push(`    local ${variable} = getNodeByName ${maxString(object.name)} exact:true`);
      body.push(`    if ${variable} == undefined do throw ${maxString(`Required scene object not found: ${object.name}`)}`);
    } else {
      body.push(`    local ${variable} = undefined -- ${sanitizeComment(object.id)} has no reliable scene name`);
    }
  }
  if (program.initialObjects.length > 0) body.push("");

  for (const operation of program.operations) {
    try {
      renderOperation(operation, {
        body,
        variableByObjectId,
        latestModifierByObjectId,
        rendererState
      });
    } catch (error) {
      const message = `${operation.id}: ${error.message}`;
      skipped.push(message);
      if (program.complete || options.allowPartial === false) throw new Error(message);
      body.push(`    -- SKIPPED ${sanitizeComment(message)}`);
    }
  }

  body.push("  )");
  body.push("  catch");
  body.push("  (");
  body.push("    local umr_error = getCurrentException()");
  body.push("    enableSceneRedraw()");
  body.push("    redrawViews()");
  body.push("    format \"UMR replay failed: %\\n\" umr_error");
  body.push("    throw()");
  body.push("  )");
  body.push("  enableSceneRedraw()");
  body.push("  redrawViews()");
  body.push(")");
  body.push("");

  return {
    script: body.join("\n"),
    skipped,
    partial: program.complete !== true || skipped.length > 0,
    renderedOperationCount: program.operations.length - skipped.length
  };
}

function renderOperation(operation, context) {
  const { body, variableByObjectId, latestModifierByObjectId, rendererState } = context;
  body.push(`    -- ${operation.id}: ${operation.kind}`);
  switch (operation.kind) {
    case "create_primitive": {
      const className = resolveClass(PRIMITIVE_CLASSES, operation.className, "primitive");
      const objectId = operation.resultObjectIds[0];
      const variable = objectVariable(variableByObjectId.size + 1);
      variableByObjectId.set(objectId, variable);
      body.push(`    local ${variable} = ${className}()`);
      if (operation.objectName) body.push(`    ${variable}.name = ${maxString(operation.objectName)}`);
      renderParameters(body, variable, operation.parameters);
      renderTransform(body, [variable], operation.transform);
      break;
    }
    case "select_objects": {
      const variables = resolveTargets(operation, variableByObjectId);
      if (operation.selectionMode === "clear") body.push("    clearSelection() ");
      else if (operation.selectionMode === "replace") body.push(`    select ${nodeArray(variables)}`);
      else if (operation.selectionMode === "add") body.push(`    selectMore ${nodeArray(variables)}`);
      else if (operation.selectionMode === "remove") body.push(`    deselect ${nodeArray(variables)}`);
      break;
    }
    case "transform": {
      renderTransform(body, resolveTargets(operation, variableByObjectId), operation.transform);
      break;
    }
    case "add_modifier": {
      const className = resolveClass(MODIFIER_CLASSES, operation.className, "modifier");
      for (const objectId of operation.targetObjectIds) {
        const objectVariableName = requireObjectVariable(variableByObjectId, objectId);
        rendererState.modifierCounter += 1;
        const modifierVariable = `umr_mod_${rendererState.modifierCounter}_${safeIdentifier(objectId)}`;
        body.push(`    local ${modifierVariable} = ${className}()`);
        renderParameters(body, modifierVariable, operation.parameters);
        body.push(`    addModifier ${objectVariableName} ${modifierVariable}`);
        latestModifierByObjectId.set(objectId, modifierVariable);
      }
      break;
    }
    case "set_parameters": {
      for (const objectId of operation.targetObjectIds) {
        const target = operation.propertyTarget === "latest_modifier"
          ? latestModifierByObjectId.get(objectId)
          : requireObjectVariable(variableByObjectId, objectId);
        if (!target) throw new Error(`object ${objectId} has no modifier created in this script`);
        renderParameters(body, target, operation.parameters);
      }
      break;
    }
    case "set_pivot": {
      const pivotMode = operation.parameters.find((parameter) => parameter.name === "pivotMode")?.value;
      const referenceObjectId = operation.parameters.find((parameter) => parameter.name === "referenceObjectId")?.value;
      const referenceVariable = pivotMode === "match_object_center"
        ? requireObjectVariable(variableByObjectId, referenceObjectId)
        : null;
      for (const variable of resolveTargets(operation, variableByObjectId)) {
        if (pivotMode === "center_to_object") body.push(`    ${variable}.pivot = ${variable}.center`);
        else if (pivotMode === "match_object_center") body.push(`    ${variable}.pivot = ${referenceVariable}.center`);
        else if (operation.transform?.position) body.push(`    ${variable}.pivot = ${point3(operation.transform.position)}`);
        else throw new Error("set_pivot has no supported exact pivot position");
      }
      break;
    }
    case "clone_objects": {
      const clonedVariables = [];
      const cloneType = String(
        operation.parameters.find((parameter) => parameter.name === "cloneType")?.value ?? "Copy"
      ).toLowerCase();
      const cloneCommand = cloneType === "instance"
        ? "instance"
        : cloneType === "reference" ? "reference" : "copy";
      operation.targetObjectIds.forEach((sourceId, index) => {
        const source = requireObjectVariable(variableByObjectId, sourceId);
        const resultId = operation.resultObjectIds[index];
        const result = objectVariable(variableByObjectId.size + 1);
        variableByObjectId.set(resultId, result);
        clonedVariables.push(result);
        body.push(`    local ${result} = ${cloneCommand} ${source}`);
        if (operation.objectName && operation.resultObjectIds.length === 1)
          body.push(`    ${result}.name = ${maxString(operation.objectName)}`);
      });
      renderTransform(body, clonedVariables, operation.transform);
      break;
    }
    case "delete_objects": {
      body.push(`    delete ${nodeArray(resolveTargets(operation, variableByObjectId))}`);
      break;
    }
    case "convert_to_poly": {
      for (const variable of resolveTargets(operation, variableByObjectId))
        body.push(`    convertToPoly ${variable}`);
      break;
    }
    case "other":
      throw new Error("operation requires an unsupported MAXScript backend capability");
    default:
      throw new Error(`unsupported operation kind ${operation.kind}`);
  }
  body.push("");
}

function renderParameters(body, target, parameters) {
  for (const parameter of parameters) {
    const property = maxProperty(parameter.name);
    body.push(`    if isProperty ${target} #${property} then setProperty ${target} #${property} ${maxLiteral(parameter.value)} else format ${maxString(`UMR: property ${property} not found on %\\n`)} ${target}`);
  }
}

function renderTransform(body, variables, transform) {
  if (!transform || transform.mode === "none") return;
  const coordinateSystem = ["world", "local", "view", "parent"].includes(transform.coordinateSystem)
    ? transform.coordinateSystem
    : "world";
  for (const variable of variables) {
    if (transform.mode === "absolute") {
      if (transform.position) body.push(`    ${variable}.position = ${point3(transform.position)}`);
      if (transform.rotationEulerDegrees)
        body.push(`    ${variable}.rotation = ${eulerAngles(transform.rotationEulerDegrees)}`);
      if (transform.scalePercent)
        body.push(`    ${variable}.scale = ${point3(transform.scalePercent.map((value) => value / 100))}`);
    } else {
      if (transform.position)
        body.push(`    in coordsys ${coordinateSystem} move ${variable} ${point3(transform.position)}`);
      if (transform.rotationEulerDegrees)
        body.push(`    in coordsys ${coordinateSystem} rotate ${variable} ${eulerAngles(transform.rotationEulerDegrees)}`);
      if (transform.scalePercent)
        body.push(`    in coordsys ${coordinateSystem} scale ${variable} ${point3(transform.scalePercent.map((value) => value / 100))}`);
    }
  }
}

function resolveTargets(operation, variables) {
  return operation.targetObjectIds.map((id) => requireObjectVariable(variables, id));
}

function requireObjectVariable(variables, id) {
  const variable = variables.get(id);
  if (!variable) throw new Error(`object ${id} has no script binding`);
  return variable;
}

function resolveClass(registry, raw, kind) {
  const normalized = normalizeClass(raw);
  const resolved = registry.get(normalized);
  if (!resolved) throw new Error(`unsupported ${kind} class ${raw}`);
  return resolved;
}

function normalizeClass(value) {
  return String(value ?? "").toLowerCase().replace(/[^a-z0-9]+/g, "");
}

function maxProperty(value) {
  const normalized = String(value ?? "").toLowerCase().replace(/[^a-z0-9]+/g, "");
  if (!normalized) throw new Error(`invalid property name ${value}`);
  return PROPERTY_ALIASES.get(normalized) ?? normalized;
}

function maxLiteral(value) {
  if (value === null) return "undefined";
  if (typeof value === "string") return maxString(value);
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number" && Number.isFinite(value)) return numberLiteral(value);
  throw new Error(`unsupported parameter value ${value}`);
}

function point3(values) {
  return `[${values.map(numberLiteral).join(", ")}]`;
}

function eulerAngles(values) {
  return `(eulerAngles ${values.map(numberLiteral).join(" ")})`;
}

function nodeArray(variables) {
  return `#(${variables.join(", ")})`;
}

function maxString(value) {
  return `\"${String(value).replaceAll("\\", "\\\\").replaceAll("\"", "\\\"").replaceAll("\r", "\\r").replaceAll("\n", "\\n")}\"`;
}

function numberLiteral(value) {
  if (!Number.isFinite(value)) throw new Error(`invalid numeric value ${value}`);
  if (Object.is(value, -0)) return "0.0";
  return Number.isInteger(value) ? `${value}.0` : String(value);
}

function objectVariable(index) {
  return `umr_obj_${index}`;
}

function safeIdentifier(value) {
  return String(value).replace(/[^a-zA-Z0-9_]+/g, "_").replace(/^([0-9])/, "_$1");
}

function sanitizeComment(value) {
  return String(value ?? "").replace(/[\r\n]+/g, " ").trim();
}
