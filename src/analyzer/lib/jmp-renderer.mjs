import {randomUUID} from 'node:crypto';
import {validateJmpProgram} from './jmp-program.mjs';
const quote=s=>{if(/["\\\r\n]/.test(s))throw Error('Unsafe JSL literal');return '"'+s+'"';};
const title=s=>s[0].toUpperCase()+s.slice(1);
const literal=v=>v===null?'.':typeof v==='number'?String(v):quote(v);
// Compile validated data only. Never Parse/Eval a model-provided string or source path.
export function renderJmp(program,validation={},options={}){
  const mapVersion=program.apiCatalogVersion==='jmp-jsl-18-v1'?'18':'19.1';
  if(options.target&&options.target.apiCatalogVersion!==program.apiCatalogVersion)throw Error('JMP renderer version mismatch');
  const catalog=validateJmpProgram(program,{...validation,apiCatalogVersion:options.target?.apiCatalogVersion??program.apiCatalogVersion,final:true});
  const runId=options.runId??randomUUID();
  if(!/^[a-zA-Z0-9_-]{1,80}$/.test(runId))throw Error('Invalid run ID');
  const lines=[
    '// Generated by the fixed JMP recorder compiler. Not evidence of recording equivalence.',
    `// JMP ${options.target?.version??mapVersion}: open this file in the Script Editor, then Edit > Run Script (no selection).`,
    '// Standalone final-state replay: table data and supported analyses are embedded.',
    '// No JSON, recorder, Node.js, API key or source data file is required.',
    '// Creates a new Documents/JMPRecorderReplays subdirectory; refuses overwrite on rerun.',
    'Names Default To Here(1);',
    'root = Convert File Path("$DOCUMENTS") || "/JMPRecorderReplays/";',
    'If(!Directory Exists(root), Create Directory(root));',
    `out = root || ${quote(runId+'/')};`,
    'If(Directory Exists(out), Throw("Replay directory already exists; refusing overwrite"));',
    'Create Directory(out);',
    'Save Text File(out || "execution-status.txt", "started; sourceRecordingCompared=false");',
    'Try('
  ];
  const checks=(t,v)=>{
    const result=[`If(N Rows(${v}) != ${t.rowCount} | N Cols(${v}) != ${t.columns.length}, Throw("Row/column inventory mismatch"));`];
    t.columns.forEach((c,i)=>{
      const ref=`Column(${v}, ${i+1})`;
      result.push(`If((${ref} << Get Name) != ${quote(c.name)}, Throw("Column name/order mismatch"));`,
        `If(Lowercase(${ref} << Get Data Type) != ${quote(c.dataType)}, Throw("Data type mismatch"));`,
        `If(Lowercase(${ref} << Get Modeling Type) != ${quote(c.modelingType)}, Throw("Modeling type mismatch"));`);
      c.values.forEach((value,j)=>result.push(value===null
        ?`If(!Is Missing(${ref}[${j+1}]), Throw("Missing value mismatch"));`
        :typeof value==='number'
          ?`If(Is Missing(${ref}[${j+1}]) | Abs(${ref}[${j+1}] - (${literal(value)})) > ${Math.max(1e-12,Math.abs(value)*1e-12)}, Throw("Cell value mismatch"));`
          :`If(${ref}[${j+1}] != ${literal(value)}, Throw("Cell text mismatch"));`));
    });
    return result;
  };
  catalog.tables.forEach((t,i)=>{
    const v='t'+i, f=quote(t.name+'.jmp');
    // JMP creates a default Column 1 when New Table receives no columns.
    // Declare every intended column in the constructor, avoiding that phantom column.
    const columns=t.columns.map(c=>`New Column(${quote(c.name)}, ${title(c.dataType)}, ${title(c.modelingType)}, Set Values({${c.values.map(literal).join(', ')}}))`);
    lines.push(`${v} = New Table(${quote(t.name)}, Add Rows(${t.rowCount}),\n  ${columns.join(',\n  ')});`);
    lines.push(...checks(t,v));
    const reportNames=[];
    catalog.reports.filter(r=>r.tableId===t.id).forEach((r,k)=>{
      const ref=id=>`Column(${v}, ${quote(t.columns.find(c=>c.id===id).name)})`;
      const rv=`r${i}_${k}`,rn='Recorder_'+r.reportId; reportNames.push(rn);
      const expression=r.kind==='distribution'
        ?`Distribution(${r.columnIds.map(id=>`Continuous Distribution(Column(${ref(id)}))`).join(', ')})`
        :`Bivariate(Y(${ref(r.yColumnId)}), X(${ref(r.xColumnId)})${r.fitLine?', Fit Line(1)':''})`;
      lines.push(`${rv} = ${v} << ${expression};`,
        `${rv} << Save Script To Data Table(${quote(rn)}, <<Prompt(0), <<Replace(0));`,
        `Save Text File(out || ${quote('report-'+r.reportId+'-before.xml')}, Report(${rv}) << Get XML);`);
    });
    lines.push(`${v} << Save(out || ${f});`, `Close(${v}, NoSave);`,`${v} = Open(out || ${f});`,...checks(t,v));
    for(const rn of reportNames)lines.push(`If(Is Empty(${v} << Get Property(${quote(rn)})), Throw("Saved analysis script missing"));`,`${v} << Run Script(${quote(rn)});`);
    lines.push(`Save Text File(out || ${quote('table-'+t.id+'-verified.txt')}, "Rows, column identity, data/modeling types and every cell verified after reopen. Analysis scripts present and invoked.");`);
  });
  lines.push('Save Text File(out || "execution-status.txt", "saved_reopened_data_verified; analysis_statistics_not_independently_compared; sourceRecordingCompared=false");',
    ', Save Text File(out || "execution-status.txt", "failed: " || Char(exception_msg)); Throw(exception_msg);',
    ');', 'New Window("JMP Recorder verification", Text Box("Native output: " || out || "  Data assertions passed. Source-recording equivalence needs independent comparison."));');
  return lines.join('\r\n')+'\r\n';
}
